#!/usr/bin/env node
/**
 * Regenerate the DSH OC home-logo artwork shipped in `tui-branding/art.ts`.
 *
 * The logo is rendered with the `figlet` npm package (devDependency) so the
 * source art stays reproducible. Two columns ("DSH" and "OC") are rendered
 * separately and combined at render time by the TUI plugin, which lets the
 * plugin colorize DSH with the theme info color and OC with the bold text
 * color.
 *
 * Usage:
 *   node scripts/generate-tui-branding-art.mjs [font]
 *
 * Defaults to the "Slant" font. Run `pnpm run branding:art` to regenerate.
 */

import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import figlet from "figlet"

const root = fileURLToPath(new URL("..", import.meta.url))
const font = process.argv[2] ?? "Slant"
const text = "DSH OC"

function render(word) {
  const rows = figlet.textSync(word, { font }).split("\n")
  // figlet emits a trailing empty row; drop it and any other fully blank rows
  // so the plugin only renders visible glyph rows.
  const visible = rows.filter((row, index) => row.trim().length > 0 || index < 5)
  const width = Math.max(...visible.map((row) => row.length))
  return visible.map((row) => row.trimEnd().padEnd(width, " "))
}

const dsh = render("DSH")
const oc = render("OC")

if (dsh.length !== oc.length) {
  throw new Error(`DSH (${dsh.length} rows) and OC (${oc.length} rows) must align`)
}

const output = `/**
 * Generated by scripts/generate-tui-branding-art.mjs — do not edit by hand.
 * Font: ${font} (figlet, "DSH OC")
 */

export const BRANDING_FONT = ${JSON.stringify(font)}

/** "DSH" rendered in figlet ${font}. */
export const DSH = ${JSON.stringify(dsh, null, 2)}

/** "OC" rendered in figlet ${font}. */
export const OC = ${JSON.stringify(oc, null, 2)}
`

const target = join(root, "tui-branding", "art.ts")
writeFileSync(target, output)
console.log(`wrote ${target} (${font}, ${dsh.length} rows, ${dsh[0].length + 3 + oc[0].length} cols combined)`)
